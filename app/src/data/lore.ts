/** 解锁条件胶囊文案 */
export function lockLabel(v: LoreVolume): string {
  const lock = v.lock
  if (lock.kind === 'free') return '初始解锁'
  if (lock.kind === 'mist') return '迷雾未散'
  if (lock.kind === 'tier') return lock.tier === 'xuan' ? '玄阶可启' : '天阶 · 九卷齐'
  return Object.entries(lock.cost)
    .map(([suit, n]) => `${{ spade: '♠', heart: '♥', club: '♣', diamond: '♦' }[suit as Suit]} ×${n}`)
    .join(' ')
}
